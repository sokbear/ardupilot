def edge(box, side):
    _, cx, cy, w, h, _ = box
    if side == "L":
        return (cx - w / 2, cy)
    if side == "R":
        return (cx + w / 2, cy)
    if side == "T":
        return (cx, cy + h / 2)
    if side == "B":
        return (cx, cy - h / 2)


