def draw_diagram():
    fig, ax = plt.subplots(figsize=(16, 10), dpi=200)
    ax.set_xlim(0, 16.5)
    ax.set_ylim(0, 10)
    ax.axis("off")

    # связи (под боксами)
    for fr, fs, to, ts, ckey, label, style, rad, (ldx, ldy) in CONN:
        p1 = edge(BOXES[fr], fs)
        p2 = edge(BOXES[to], ts)
        color = COL[ckey]
        if style == "<->":
            arrowstyle = "<|-|>"
            ls = "-"
        else:
            arrowstyle = "-|>"
            ls = style
        arrow = FancyArrowPatch(
            p1, p2,
            connectionstyle=f"arc3,rad={rad}",
            arrowstyle=arrowstyle,
            mutation_scale=16,
            linewidth=2.0,
            linestyle=ls,
            color=color,
            zorder=1,
        )
        ax.add_patch(arrow)
        mx = (p1[0] + p2[0]) / 2 + ldx
        my = (p1[1] + p2[1]) / 2 + ldy
        ax.text(mx, my, label, fontsize=8.5, color=color, ha="center", va="center",
                bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85),
                zorder=3)

    # боксы
    for key, (name, cx, cy, w, h, fc) in BOXES.items():
        box = FancyBboxPatch(
            (cx - w / 2, cy - h / 2), w, h,
            boxstyle="round,pad=0.04,rounding_size=0.12",
            linewidth=1.6, edgecolor="#34495e", facecolor=fc, zorder=2,
        )
        ax.add_patch(box)
        ax.text(cx, cy, name, fontsize=9.5, ha="center", va="center",
                color="#1b2631", zorder=3, weight="bold")

    # легенда
    legend_items = [
        ("Видео (MIPI / CVBS)", COL["video"], "-"),
        ("SBUS", COL["sbus"], "-"),
        ("UART (MAVLink / линк)", COL["uart"], "-"),
        ("PWM", COL["pwm"], "-"),
        ("Радио / механика", COL["rf"], "--"),
    ]
    x0, y0 = 0.55, 5.55
    ax.add_patch(FancyBboxPatch((x0 - 0.25, y0 - 5 * 0.34 - 0.2), 3.5, 6 * 0.34 + 0.35,
                                boxstyle="round,pad=0.04", linewidth=1.0,
                                edgecolor="#bbbbbb", facecolor="white", zorder=2))
    for i, (txt, c, ls) in enumerate(legend_items):
        yy = y0 - i * 0.34
        ax.plot([x0, x0 + 0.6], [yy, yy], color=c, linewidth=2.4, linestyle=ls, zorder=3)
        ax.text(x0 + 0.75, yy, txt, fontsize=8.5, va="center", color="#1b2631", zorder=3)

    ax.set_title("Функциональная схема: «электронный пилот» (SBUS man-in-the-middle)",
                 fontsize=14, weight="bold", pad=12)
    fig.tight_layout()
    fig.savefig(DIAGRAM, bbox_inches="tight")
    plt.close(fig)
    print("diagram saved:", DIAGRAM)


